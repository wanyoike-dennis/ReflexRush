package com.inventsolutions.reflexrush.feature.game

import android.content.Context
import com.inventsolutions.reflexrush.core.audio.GameAudioCoordinator
import com.inventsolutions.reflexrush.core.feedback.GameFeedback
import com.inventsolutions.reflexrush.core.feedback.GameFeedbackCoordinator
import com.inventsolutions.reflexrush.game.GameActionResult
import com.inventsolutions.reflexrush.game.GameController
import com.inventsolutions.reflexrush.game.GameEngine
import com.inventsolutions.reflexrush.game.GameLoop
import com.inventsolutions.reflexrush.game.GameLoopUpdate
import com.inventsolutions.reflexrush.game.GameMode
import com.inventsolutions.reflexrush.game.GameSessionConfig
import com.inventsolutions.reflexrush.game.GameState
import com.inventsolutions.reflexrush.game.GameStatus
import com.inventsolutions.reflexrush.game.GameplayEvent

/** Result of a player command after its gameplay events have been routed to audio and feedback. */
internal data class SessionAction(
    val action: GameActionResult,
    val feedback: GameFeedback?
)

/** A simulation update and any player-facing feedback generated by that frame. */
internal data class SessionFrame(
    val update: GameLoopUpdate,
    val feedback: GameFeedback?
)

/**
 * Owns the active game session's controller, frame cadence, and gameplay event side effects.
 * The Compose screen observes state and renders it; this runtime routes session commands.
 */
internal class GameSessionRuntime(context: Context, mode: GameMode) {
    val controller = GameController(GameEngine(GameSessionConfig.forMode(mode)))

    private val audioCoordinator = GameAudioCoordinator(context.applicationContext)
    private val feedbackCoordinator = GameFeedbackCoordinator(context.applicationContext)
    private val gameLoop = GameLoop()

    fun start(): SessionAction = dispatch(controller.start())

    fun tapTarget(targetId: Long): SessionAction = dispatch(controller.tapTarget(targetId))

    fun resetLoop() = gameLoop.reset()

    fun setGameActive(status: GameStatus, isResumed: Boolean) {
        audioCoordinator.setGameActive(status, isResumed)
    }

    fun onFrame(frameNanos: Long, previousUiState: GameState): SessionFrame? {
        val update = gameLoop.onFrame(frameNanos, previousUiState, controller) ?: return null
        return SessionFrame(update, routeEvents(update.action.events))
    }

    fun playPersonalBest() = audioCoordinator.playPersonalBest()

    fun release() = audioCoordinator.release()

    private fun dispatch(action: GameActionResult) =
        SessionAction(action, routeEvents(action.events))

    private fun routeEvents(events: List<GameplayEvent>): GameFeedback? {
        audioCoordinator.playEvents(events)
        return feedbackCoordinator.handle(events)
    }
}
